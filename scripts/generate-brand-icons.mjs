/**
 * Extracts just the brand icons this site uses from `simple-icons` into
 * data/brand-icons.ts.
 *
 * The full package carries 3400+ icons. ProjectCard renders inside the client
 * `ProjectFilter`, so importing the package directly would ship all of them to
 * the browser. Pinning a small generated subset keeps the client bundle tiny.
 *
 * Re-run with: node scripts/generate-brand-icons.mjs
 *
 * Icons are CC0 1.0 (public domain). The trademarks they depict remain the
 * property of their respective owners and are used here only to identify the
 * technology or organisation being referred to.
 */
import * as si from 'simple-icons'
import { writeFileSync } from 'node:fs'

const SLUGS = [
  'accenture', 'generalmotors', 'cadillac',
  'android', 'kotlin', 'openjdk', 'cplusplus', 'qt',
  'jetpackcompose', 'gradle', 'linux', 'git', 'eclipseide',
]

/** "#A100FF" | "A100FF" -> [161, 0, 255] */
function rgb(hex) {
  const h = hex.replace('#', '')
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16))
}

/** WCAG relative luminance, 0 (black) to 1 (white). */
function luminance(hex) {
  const [r, g, b] = rgb(hex).map((v) => {
    const c = v / 255
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
  })
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}

/** Blends `hex` toward `target` by `amount` (0-1). */
function mix(hex, target, amount) {
  const a = rgb(hex)
  const b = rgb(target)
  return (
    '#' +
    a
      .map((v, i) => Math.round(v * (1 - amount) + b[i] * amount).toString(16).padStart(2, '0'))
      .join('')
  )
}

/**
 * Brand colours are authored for a white page. Near-black marks (Cadillac,
 * OpenJDK) disappear on the dark theme and very light marks wash out on the
 * light one, so blend each toward legibility per theme while keeping the hue.
 */
function forTheme(hex) {
  const l = luminance(hex)
  const base = `#${hex.replace('#', '').toLowerCase()}`
  // Grade the lightening: a flat blend turns mid-dark brands (C++ blue) into
  // pale grey, so lift only as much as legibility needs and keep the hue.
  const lift = Math.min(0.72, Math.max(0.35, 0.35 + (0.3 - l) * 1.25))
  return {
    hexLight: l > 0.62 ? mix(hex, '#000000', 0.42) : base,
    hexDark: l < 0.3 ? mix(hex, '#ffffff', lift) : base,
  }
}

const icons = {}
for (const slug of SLUGS) {
  const icon = si[`si${slug.charAt(0).toUpperCase()}${slug.slice(1)}`]
  if (!icon) throw new Error(`simple-icons has no icon for "${slug}"`)
  const { hexLight, hexDark } = forTheme(icon.hex)
  icons[slug] = { title: icon.title, hexLight, hexDark, path: icon.path }
}

const file = `// GENERATED by scripts/generate-brand-icons.mjs — do not edit by hand.
// Source: simple-icons (CC0 1.0). Trademarks belong to their respective owners
// and appear here solely to identify the technology or organisation named.

export type BrandIcon = {
  /** Official brand name, used as the accessible label. */
  title: string
  /** Brand colour, darkened if needed to stay legible on a light background. */
  hexLight: string
  /** Brand colour, lightened if needed to stay legible on a dark background. */
  hexDark: string
  /** SVG path data, drawn in a 24x24 viewBox. */
  path: string
}

export const brandIcons = ${JSON.stringify(icons, null, 2)} as const satisfies Record<string, BrandIcon>

export type BrandSlug = keyof typeof brandIcons
`

writeFileSync(new URL('../data/brand-icons.ts', import.meta.url), file)
console.log(`wrote data/brand-icons.ts with ${Object.keys(icons).length} icons`)
